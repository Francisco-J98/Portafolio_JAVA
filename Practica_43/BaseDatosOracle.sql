--La salida será un listado con todas las notas. En lugar del id de asignatura e id de alumno, deben aparecer el nombre de la asignatura y el nombre del alumno.

--Método 1:
SELECT NOTAS.ID_NOTA,ASIGNATURAS.NOM_ASI,ALUMNOS.APENOM,NOTAS.NOTA
FROM NOTAS, ASIGNATURAS, ALUMNOS
WHERE NOTAS.C_ASI = ASIGNATURAS.COD AND NOTAS.D_ALU = ALUMNOS.DNI
ORDER BY ID_NOTA ASC;

--Método 2:
SELECT NOTAS.ID_NOTA,ASIGNATURAS.NOM_ASI,ALUMNOS.APENOM,NOTAS.NOTA
FROM NOTAS
INNER JOIN ASIGNATURAS
ON NOTAS.C_ASI = ASIGNATURAS.COD
INNER JOIN ALUMNOS
ON NOTAS.D_ALU = ALUMNOS.DNI
ORDER BY NOTAS.ID_NOTA ASC;

